// 把 JLPT 題庫的中文詳解(q.x)翻成英文 → jlpt-questions-en.js(window.JLPT_Q_EN = {id: 英文詳解})
//
// 為什麼不直接改 jlpt-questions.js:那檔是人工維護的主資料,翻譯是衍生物,
// 分開放才不會在下次有人編題目時被覆蓋,也方便重翻。
//
// 走 `claude -p`(用 Mia 的訂閱,不需要 ANTHROPIC_API_KEY)。
// 一次送一批,每批要求回 JSON,壞掉的那批自動重試一次再跳過(不讓單批毀掉整輪)。
//
// 用法:
//   node scripts/gen-drill-en.mjs 20          # 只翻前 20 題(抽驗品質用)
//   node scripts/gen-drill-en.mjs             # 全部,已翻過的跳過(可中斷續跑)
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

// ⚠️ 不能用 promisify(execFile) 餵 prompt:execFile 沒有 input 這個選項(那是 sync 版的),
//    會靜悄悄地送出空的 stdin,claude 只回一句 "no stdin data received"。
function run(cmd, args, input) {
  return new Promise((resolve, reject) => {
    const p = spawn(cmd, args, { stdio: ['pipe', 'pipe', 'pipe'] });
    let out = '', err = '';
    p.stdout.on('data', d => { out += d; });
    p.stderr.on('data', d => { err += d; });
    p.on('error', reject);
    p.on('close', code => code === 0 ? resolve({ stdout: out }) : reject(new Error(err.slice(0, 200) || 'exit ' + code)));
    p.stdin.end(input);
  });
}
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'jlpt-questions-en.js');
const LIMIT = Number(process.argv[2] || 0);
const BATCH = 8;

function loadQ() {
  const src = fs.readFileSync(path.join(ROOT, 'jlpt-questions.js'), 'utf8');
  const sb = {};
  new Function('window', src + ';window.__Q=(typeof JLPT_Q!=="undefined")?JLPT_Q:window.JLPT_Q;')(sb);
  return sb.__Q || [];
}
function loadDone() {
  if (!fs.existsSync(OUT)) return {};
  const sb = {};
  try { new Function('window', fs.readFileSync(OUT, 'utf8'))(sb); } catch { return {}; }
  return sb.JLPT_Q_EN || {};
}

const SYS = `You translate Japanese-grammar explanations from Traditional Chinese into English for a JLPT study app.

Rules:
- Keep ALL Japanese text exactly as-is (kana, kanji, particles). Never translate or romanise Japanese.
- Keep HTML tags (<b>, <br>) exactly where they are.
- Natural, concise English a learner can follow. Explain the grammar, don't just gloss the Chinese.
- Keep the same structure and line breaks as the original.
- Output ONLY a JSON object mapping id -> translated explanation. No markdown fence, no commentary.`;

const all = loadQ().filter(q => q.x);
const done = loadDone();
const todo = all.filter(q => !done[q.id]).slice(0, LIMIT || all.length);
console.log(`題庫 ${all.length} 題,已翻 ${Object.keys(done).length},這次要翻 ${todo.length}`);

async function translate(batch) {
  const payload = {};
  batch.forEach(q => { payload[q.id] = q.x; });
  const prompt = SYS + '\n\nTranslate these:\n' + JSON.stringify(payload, null, 1);
  const { stdout } = await run('claude', ['-p'], prompt);
  const m = stdout.match(/\{[\s\S]*\}/);
  if (!m) throw new Error('沒有 JSON');
  return JSON.parse(m[0]);
}

// 一批 claude -p 要跑 20~30 秒,893 題排隊跑會要一小時。開 4 條並行壓到 15 分鐘上下。
// (沒開更多是因為每條都是一個 claude 進程,開太多會拖垮機器 —— 她的電腦被我鈍過。)
const PAR = 4;
let ok = 0, bad = 0, started = 0, finished = 0;
const batches = [];
for (let i = 0; i < todo.length; i += BATCH) batches.push(todo.slice(i, i + BATCH));

function save() {
  fs.writeFileSync(OUT, `// Generated by scripts/gen-drill-en.mjs — JLPT 詳解英文版\nwindow.JLPT_Q_EN = ${JSON.stringify(done)};\n`);
}

async function worker() {
  while (started < batches.length) {
    const batch = batches[started++];
    let got = null;
    for (let tries = 0; tries < 2 && !got; tries++) {
      try { got = await translate(batch); }
      catch (e) { if (tries) console.log(`\n  一批失敗(${String(e.message).slice(0, 60)}),跳過`); }
    }
    for (const q of batch) {
      if (got && typeof got[q.id] === 'string' && got[q.id].trim()) { done[q.id] = got[q.id].trim(); ok++; }
      else bad++;
    }
    finished++;
    save();
    process.stdout.write(`\r  進度 ${finished}/${batches.length} 批  成功 ${ok} 失敗 ${bad}`);
  }
}
await Promise.all(Array.from({ length: PAR }, worker));
save();
console.log(`\n完成:成功 ${ok},失敗 ${bad},累計 ${Object.keys(done).length} 題有英文`);
