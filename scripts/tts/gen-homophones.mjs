#!/usr/bin/env node
// 同音不同重音的單字各自產音檔(2026-10-09)。
// 單字平常播「讀音」音檔(せんせい),同音字共用一個 → 宣誓⓪ 會聽到 先生③ 的重音。
// 這裡對「重音跟該讀音音檔不同」的字,用讀音合成+塑形成自己的重音,存成 audio/tts/<hash('hw|'+字)>.mp3,
// 清單寫 audio/tts/homophones.js → window.__TTS_HW {字: hash};speak()/wordSpeakKey() 優先查它。
// 獨立於 manifest.js,所以重跑 tts:collect/generate 不會洗掉。N5/N4 另產 tts-v 8/13 人聲。
// 用法:node scripts/tts/gen-homophones.mjs   (需要 VOICEVOX 開著;新增單字/音高資料後重跑)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, OUT_DIR, SPEAKER, TEXTS_JSON, hashText, loadOverrides, applyOverrides, audioQuery, synthesis, checkEngine, wavToMp3, shapePitch } from './_lib.mjs';

const VOICES = [8, 13];
const W = {}; new Function('window', fs.readFileSync(path.join(ROOT, 'pitch-accent.js'), 'utf8'))(W);
const PITCH = W.PITCH;
const inTexts = new Set(JSON.parse(fs.readFileSync(TEXTS_JSON, 'utf8')).map(t => t.text));
const overrides = loadOverrides();
const VMAN_F = path.join(ROOT, 'audio/tts-v/manifest.js');
const VMAN = JSON.parse(fs.readFileSync(VMAN_F, 'utf8').replace(/^[\s\S]*?window\.__TTS_V = /, '').replace(/;\s*$/, ''));

// 讀音 → 該讀音音檔用的重音(級別最低的字先佔,同 regen-pitch.mjs)
const keyPitch = new Map(), list = [];
const all = [];
for (const lv of ['n5', 'n4', 'n3', 'n2', 'n1']) {
  const src = fs.readFileSync(path.join(ROOT, `vocab-${lv}.js`), 'utf8');
  for (const m of src.matchAll(/\{w:"([^"]+)",r:"([^"]*)"/g)) {
    const [, w, r] = m; const n = PITCH[w + '|' + r];
    if (typeof n !== 'number' || !r) continue;
    all.push({ w, r, n, lv });
    if (inTexts.has(r) && !keyPitch.has(r)) keyPitch.set(r, n);
  }
}
const seen = new Set();
for (const it of all) {
  if (it.w === it.r || !keyPitch.has(it.r) || keyPitch.get(it.r) === it.n || seen.has(it.w)) continue;
  seen.add(it.w); list.push(it);
}

console.log('VOICEVOX', await checkEngine(), '· 同音不同重音', list.length, '字');
const HW = {}; let made = 0, skip = [];
for (const it of list) {
  const hash = hashText('hw|' + it.w);
  const sps = [SPEAKER, ...((it.lv === 'n5' || it.lv === 'n4') ? VOICES : [])];
  let ok = true;
  for (const sp of sps) {
    const q = await audioQuery(applyOverrides(it.r, overrides), sp);
    if (q.accent_phrases.length !== 1) { ok = false; break; }
    const wav = await synthesis(shapePitch(q, it.n), sp);
    if (sp === SPEAKER) wavToMp3(wav, path.join(OUT_DIR, hash + '.mp3'));
    else { const d = path.join(ROOT, 'audio/tts-v', String(sp)); wavToMp3(wav, path.join(d, hash + '.mp3')); (VMAN[sp] = VMAN[sp] || {})[hash] = 1; }
    made++;
  }
  if (ok) HW[it.w] = hash; else skip.push(it.w);
}
fs.writeFileSync(path.join(OUT_DIR, 'homophones.js'), '// Generated by scripts/tts/gen-homophones.mjs — do not edit by hand. {字: hash} 同音不同重音的字用自己的音檔\nwindow.__TTS_HW = ' + JSON.stringify(HW) + ';\n');
fs.writeFileSync(VMAN_F, '// Generated by scripts/tts/gen-voices.mjs — do not edit by hand. {speaker:{hash:1}}\nwindow.__TTS_V = ' + JSON.stringify(VMAN) + ';\n');
console.log(`產 ${made} 檔,收 ${Object.keys(HW).length} 字`, skip.length ? '· 略過(多語段) ' + skip.join(' ') : '');
