// 刷題的「整句翻譯」英文版 → jlpt-q-trans-en.js(window.JLPT_Q_TRANS_EN)
//
// 中文版(jlpt-q-trans.js)已經存在,但英文介面的人按「Show translation」會跳出中文。
// 這支直接從日文題幹翻英文(不是把中文再翻一手),中文版只當參考避免歧義。
//
// 用法:node scripts/gen-drill-trans-en.mjs [題數]
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';

function run(cmd, args, input) {
  return new Promise((resolve, reject) => {
    const p = spawn(cmd, args, { stdio: ['pipe', 'pipe', 'pipe'] });
    let out = '', err = '';
    p.stdout.on('data', d => { out += d; });
    p.stderr.on('data', d => { err += d; });
    p.on('error', reject);
    p.on('close', c => c === 0 ? resolve(out) : reject(new Error(err.slice(0, 200) || 'exit ' + c)));
    p.stdin.end(input);
  });
}
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'jlpt-q-trans-en.js');
const LIMIT = Number(process.argv[2] || 0);
const BATCH = 12, PAR = 4;

function load(file, key) {
  const sb = {};
  try { new Function('window', fs.readFileSync(path.join(ROOT, file), 'utf8') + `;window.__v=(typeof ${key}!=="undefined")?${key}:window.${key};`)(sb); }
  catch { return null; }
  return sb.__v;
}
const Q = load('jlpt-questions.js', 'JLPT_Q') || [];
const ZH = load('jlpt-q-trans.js', 'JLPT_Q_TRANS') || {};
const done = (fs.existsSync(OUT) && load('jlpt-q-trans-en.js', 'JLPT_Q_TRANS_EN')) || {};

const SYS = `You translate JLPT practice sentences into English.

You get a JSON object: id -> { ja: the Japanese sentence, zh: an existing Chinese translation for reference }.
Translate the JAPANESE into natural English. Use the Chinese only to resolve ambiguity — never translate the Chinese itself.

- The sentence may contain a blank written as ( ) or 【...】 — keep that marker in the same place in the English.
- Natural everyday English, one sentence, no explanation.
- Output ONLY a JSON object mapping id -> English sentence. No markdown fence, no commentary.`;

const todo = Q.filter(q => ZH[q.id] && !done[q.id]).slice(0, LIMIT || undefined);
console.log(`有中文翻譯 ${Object.keys(ZH).length} 題,已翻英文 ${Object.keys(done).length},這次要翻 ${todo.length}`);

const batches = [];
for (let i = 0; i < todo.length; i += BATCH) batches.push(todo.slice(i, i + BATCH));
const save = () => fs.writeFileSync(OUT, `// Generated by scripts/gen-drill-trans-en.mjs — 刷題整句翻譯英文版\nwindow.JLPT_Q_TRANS_EN = ${JSON.stringify(done)};\n`);

let ok = 0, bad = 0, started = 0, finished = 0;
async function worker() {
  while (started < batches.length) {
    const b = batches[started++];
    const payload = {};
    b.forEach(q => { payload[q.id] = { ja: q.q || q.at || '', zh: ZH[q.id] }; });
    let got = null;
    for (let t = 0; t < 2 && !got; t++) {
      try {
        const out = await run('claude', ['-p'], SYS + '\n\nTranslate these:\n' + JSON.stringify(payload, null, 1));
        got = JSON.parse(out.match(/\{[\s\S]*\}/)[0]);
      } catch (e) { if (t) console.log(`\n  一批失敗(${String(e.message).slice(0, 60)}),跳過`); }
    }
    for (const q of b) {
      if (got && typeof got[q.id] === 'string' && got[q.id].trim()) { done[q.id] = got[q.id].trim(); ok++; }
      else bad++;
    }
    finished++; save();
    process.stdout.write(`\r  進度 ${finished}/${batches.length} 批  成功 ${ok} 失敗 ${bad}`);
  }
}
await Promise.all(Array.from({ length: PAR }, worker));
save();
console.log(`\n完成:成功 ${ok},失敗 ${bad},累計 ${Object.keys(done).length} 題有英文翻譯`);
